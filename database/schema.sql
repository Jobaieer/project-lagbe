create table if not exists public.users (
  id bigint generated by default as identity primary key,
  name text not null,
  email text not null unique,
  pass text not null,
  role text not null default 'user' check (role in ('user', 'admin')),
  created timestamptz not null default now()
);

create table if not exists public.projects (
  id bigint generated by default as identity primary key,
  title text not null,
  category text not null default 'অন্যান্য',
  cover_url text,
  course text,
  tech text,
  description text,
  price_code integer not null default 0,
  price_consult integer not null default 0,
  download_url text,
  preview_url text,
  active boolean not null default true,
  created timestamptz not null default now()
);

alter table public.projects add column if not exists category text not null default 'অন্যান্য';
alter table public.projects add column if not exists cover_url text;
alter table public.projects add column if not exists preview_url text;

create table if not exists public.orders (
  id bigint generated by default as identity primary key,
  user_id bigint not null references public.users(id) on delete cascade,
  project_id bigint not null references public.projects(id) on delete restrict,
  option text not null check (option in ('code', 'consult')),
  method text,
  trx_id text not null,
  note text not null default '',
  status text not null default 'pending'
    check (status in ('pending', 'approved', 'rejected')),
  meet_link text not null default '',
  created timestamptz not null default now()
);

create index if not exists orders_user_id_idx on public.orders(user_id);
create index if not exists orders_project_id_idx on public.orders(project_id);

create table if not exists public.notifications (
  id bigint generated by default as identity primary key,
  user_id bigint not null references public.users(id) on delete cascade,
  title text not null,
  body text not null,
  read boolean not null default false,
  created timestamptz not null default now()
);

create index if not exists notifications_user_id_idx on public.notifications(user_id);

alter table public.users enable row level security;
alter table public.projects enable row level security;
alter table public.orders enable row level security;
alter table public.notifications enable row level security;
