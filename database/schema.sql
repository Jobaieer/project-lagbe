create table if not exists public.seller_applications (
  id bigint generated by default as identity primary key,
  user_id bigint not null unique references public.users(id) on delete cascade,
  university text not null,
  university_id text not null,
  department text not null,
  institution_email text not null,
  reason text not null,
  status text not null default 'pending' check (status in ('pending', 'approved', 'rejected')),
  created timestamptz not null default now()
);

create table if not exists public.payout_requests (
  id bigint generated by default as identity primary key,
  seller_id bigint not null references public.users(id) on delete cascade,
  amount numeric(12,2) not null check (amount > 0),
  status text not null default 'pending' check (status in ('pending', 'paid', 'rejected')),
  created timestamptz not null default now()
);

create table if not exists public.seller_wallet_transactions (
  id bigint generated by default as identity primary key,
  seller_id bigint not null references public.users(id) on delete cascade,
  order_id bigint unique references public.orders(id) on delete set null,
  payout_request_id bigint references public.payout_requests(id) on delete set null,
  type text not null check (type in ('sale_credit', 'payout_debit')),
  amount numeric(12,2) not null check (amount > 0),
  note text not null default '',
  created timestamptz not null default now()
);

create index if not exists seller_wallet_transactions_seller_id_idx
